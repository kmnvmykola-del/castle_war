"""Replace only premium source meshes; export small batches for Studio upload."""
from pathlib import Path
import json
import hashlib
from export_static_meshes import catalogue,metadata,team_colours,lua,Export

ROOT=Path(__file__).resolve().parents[1]
FOLDER=ROOT/'assets/roblox_meshes'
AUTHORED=ROOT/'assets/blender/v016/premium'

def main():
    replacement=json.loads((AUTHORED/'geometry.json').read_text())
    assert len(replacement)==90 and len({a['name']for a in replacement})==90
    styles={s['Id']:s for s in json.loads((ROOT/'assets/blender/v012/styles.json').read_text())}
    teams=team_colours(); names={a['name']for a in replacement}
    previous=catalogue(); by_name={a['name']:a for a in previous}
    for asset in replacement:
        assert asset['name'].split('_')[0]in ('Storm','Dragon','Oracle')
        if asset['name']in by_name:assert asset['joint']==by_name[asset['name']]['joint']
        assert len(asset['triangles'])<=6000
        by_name[asset['name']]=asset
    merged=sorted(by_name.values(),key=lambda a:a['name'])
    models={a['name']:metadata(a,styles)for a in merged}
    signature=hashlib.sha256(json.dumps({'assets':merged,'teams':teams},sort_keys=True,separators=(',',':')).encode()).hexdigest()
    manifest=dict(Version=2,Signature=signature,Models=models)
    source='-- Generated by tools/export_premium_v016.py; ordinary imported MeshParts.\nreturn '+lua(manifest)+'\n'
    assert len(source.encode())<180000
    (ROOT/'src/MeshCatalog.luau').write_text(source,encoding='utf8')
    changed=[];reports=[]
    for skin in ('Storm','Dragon','Oracle'):
        # Keep each upload below 100 parts; colour variants share geometry.
        export=Export();export.gltf['nodes'][0]['name']='KingdomsPremium'+skin
        assets=[a for a in replacement if a['name'].startswith(skin+'_')]
        records=[export.add(a,models[a['name']],styles,teams)for a in assets]
        path=FOLDER/f'KingdomsPremium{skin}.glb';export.save(path)
        changed.extend(mesh['name']for mesh in export.gltf['meshes'])
        reports.append(dict(skin=skin,models=len(assets),meshParts=len(export.gltf['meshes']),
            triangles=sum(r['triangles']*r['variants']for r in records),records=records))
    data=dict(version='0.16',signature=signature,baseSignature=json.loads((FOLDER/'manifest.json').read_text())['signature'],
              changedModels=sorted(names),changedKeys=sorted(changed),totalModels=len(models),
              totalMeshParts=sum(1+2*m['Team']+m['Neutral']for m in models.values()),batches=reports)
    (FOLDER/'premium-manifest.json').write_text(json.dumps(data,indent=2),encoding='utf8')
    (AUTHORED/'merged-catalogue.json').write_text(json.dumps(merged,separators=(',',':')),encoding='utf8')
    for a in replacement:
        palette=[];faces=[]
        for face in a['triangles']:
            if face['c']not in palette:palette.append(face['c'])
            faces.append(face['v']+[palette.index(face['c'])+1])
        def array(values):return '{'+','.join(array(v)if isinstance(v,list)else str(v).lower()for v in values)+'}'
        legacy='return {Name="'+a['name']+'",Tint='+str(a['tint']).lower()+',Joint='+array(a['joint'])+',Vertices='+array(a['vertices'])+',Palette='+array(palette)+',Faces='+array(faces)+'}\n'
        assert len(legacy.encode())<180000,a['name']
        (ROOT/f"src/Geometry/{a['name']}.luau").write_text(legacy,encoding='utf8')
    print(json.dumps({k:v for k,v in data.items()if k not in ('changedKeys','changedModels','batches')}))

if __name__=='__main__':main()
